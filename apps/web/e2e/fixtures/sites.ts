async function main() {
  assertTestDatabase();
  const payload = await getPayload({ config });

  const ownerIds = new Map<OwnerKey, number>();
  for (const [i, o] of OWNERS.entries()) {
    const slug = `sample-${o.key}`;
    const data = {
      name: o.name,
      slug,
      city: o.city,
      about: o.about,
      contactEmail: `${o.key}@example.com`,
      phone: `+91 00000 0000${i + 1} (sample)`,
      verified: o.verified,
      verifiedOn: o.verified ? ago(30 + i * 9) : null,
      medianReplyHours: o.reply,
      sample: true,
    };
    const existing = await payload.find({
      collection: "owners",
      where: { slug: { equals: slug } },
      limit: 1,
      overrideAccess: true,
    });
    const doc = existing.docs[0]
      ? await payload.update({
          collection: "owners",
          id: existing.docs[0].id,
          data,
          overrideAccess: true,
        })
      : await payload.create({ collection: "owners", data, overrideAccess: true });
    ownerIds.set(o.key, doc.id);
  }

  let made = 0;
  for (const [i, row] of ROWS.entries()) {
    const owner = ownerIds.get(row.o);
    if (!owner) throw new Error(`No owner for ${row.id}`);
    const digital = row.lit === "digital";
    const lit = row.lit === "front-lit" || row.lit === "back-lit";
    const confirmed =
      row.avail === "unknown"
        ? null
        : row.avail === "stale"
          ? ago(45 + (i % 4) * 9)
          : ago(2 + (i % 6) * 3);
    const data = {
      _status: "published" as const,
      sample: true,
      removed: false,
      owner,
      format: row.f,
      environment:
        row.f === "bus-shelter" || row.f === "transit"
          ? ("transit" as const)
          : ("roadside" as const),
      width: row.w,
      height: row.h,
      sizeUnit: "ft" as const,
      lighting: row.lit,
      litHours: lit ? "6 pm to 11 pm" : digital ? "6 am to 11 pm" : null,
      heightAboveRoadM: row.f === "bus-shelter" || row.f === "transit" ? null : 5 + (i % 5) * 2,
      digital: digital
        ? {
            resolution: "1920 × 1080",
            spotSeconds: 10,
            loopSeconds: 60,
            advertisers: 6,
            exchanges: i % 2 ? "Not available programmatically" : null,
          }
        : {},
      country: "in",
      currency: "INR",
      city: row.city,
      locality: row.loc,
      road: row.road,
      landmark: row.mark ?? null,
      lat: row.lat,
      lng: row.lng,
      facingDeg: row.face,
      trafficDirection: row.traffic ?? null,
      verifiedLocation: row.vloc,
      lastVerifiedOn: row.vloc ? ago(6 + (i % 7) * 4) : null,
      priceDisplay: row.price,
      rate: row.rate ?? null,
      minPeriod: digital ? "1 week" : i % 3 === 0 ? "3 months" : "1 month",
      productionCost: digital
        ? null
        : `₹ ${(Math.round((row.w * row.h * 90) / 1000) * 1000).toLocaleString("en-IN")} once, by the owner`,
      taxesNote: "Taxes extra",
      notAccepted: i % 4 === 0 ? "Alcohol, tobacco" : null,
      bookedUntil: row.avail === "booked" ? ahead(18 + (i % 5) * 9) : null,
      availabilityConfirmedOn: confirmed,
      artworkSpec: digital ? "1920 × 1080 px, 10 seconds" : `${row.w} × ${row.h} ft at 30 dpi`,
      fileTypes: digital ? "MP4 or JPG" : "PDF or TIFF, CMYK",
      leadTimeDays: digital ? 2 : 7,
      audience: row.aud
        ? {
            figure: row.aud,
            metric: "weekly impressions, adults 18+",
            source: "Sample data",
            method: "Illustration only, not measured",
            measuredOn: ago(40),
          }
        : {},
      permit:
        row.permit === "none"
          ? {}
          : {
              number: `SAMPLE-${row.id.toUpperCase()}`,
              authority: "Sample authority",
              expiresOn: row.permit === "expired" ? ago(60) : ahead(200),
            },
      photos: [],
    };
    const existing = await payload.find({
      collection: "sites",
      where: { permanentId: { equals: row.id } },
      limit: 1,
      draft: true,
      overrideAccess: true,
    });
    if (existing.docs[0])
      await payload.update({
        collection: "sites",
        id: existing.docs[0].id,
        data,
        overrideAccess: true,
      });
    else
      await payload.create({
        collection: "sites",
        data: { ...data, permanentId: row.id },
        overrideAccess: true,
      });
    made += 1;
  }
  payload.logger.info(
    `Sample marketplace ready: ${OWNERS.length} owners, ${made} sites. All are labelled as samples.`,
  );
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
